/* Builds the shipped dictionary from the authored sources in data/.
 *
 *   data/curated.ts        14k words, each with an example sentence
 *   data/freedict.source.ts  FreeDict nld-eng, most of which the curated
 *                            list already covers
 *        ↓
 *   src/data/core.generated.ts      word + gloss + gender  (loaded up front)
 *   src/data/examples.generated.ts  the example sentences  (fetched lazily)
 *
 * Two things make this worth generating rather than shipping the sources:
 *
 *  - The sentences are ~68% of the data but are only ever read one word at a
 *    time (a flashcard, an expanded row). Splitting them keeps them off the
 *    critical path.
 *  - Deduplicating FreeDict against the curated list leaves only a hundred or
 *    so new words; shipping the whole file to gain those is pure weight.
 *
 * Both outputs are tab/newline-delimited strings rather than object literals:
 * same data, roughly half the bytes, and the engine parses one string literal
 * far faster than 14k object literals.
 *
 * Run with: npm run dictionary
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

/* Gender codes. "n" (none) and "u" (unknown) are deliberately different
   letters: a verb takes no article, an unglossed import has one nobody has
   established, and writing both as "" is what made 118 article-less words
   invisible for as long as they were. */
const GENDER_CODE = { de: "d", het: "h", none: "n", unknown: "u" };
const FIELD = "\t";
const RECORD = "\n";

/** Loads a TypeScript data module by transpiling it with the local esbuild.
 *  The output name is unique per module: `import()` caches by URL, so reusing
 *  one path would hand back the first module again. */
async function loadTs(entry, tmp, name) {
  const out = join(tmp, `${name}.mjs`);
  execFileSync("npx", ["esbuild", entry, "--bundle", "--format=esm", `--outfile=${out}`, "--log-level=error"], {
    stdio: ["ignore", "ignore", "inherit"],
  });
  return import(`file://${out}`);
}

function assertDelimiterFree(entries) {
  for (const e of entries) {
    for (const [field, value] of Object.entries(e)) {
      if (typeof value === "string" && /[\t\n\r]/.test(value)) {
        throw new Error(`"${e.dutch}" has a tab or newline in ${field} — it would corrupt the encoding`);
      }
    }
  }
}

function tsModule(banner, exportName, payload) {
  return (
    `${banner}\n` +
    `// AUTO-GENERATED by scripts/gen-dictionary.mjs — do not edit by hand.\n` +
    `// Edit data/curated.ts, then run \`npm run dictionary\`.\n\n` +
    `export const ${exportName} = ${JSON.stringify(payload)};\n`
  );
}

const tmp = mkdtempSync(join(tmpdir(), "woordkast-dict-"));
try {
  const { ENTRIES } = await loadTs("data/curated.ts", tmp, "curated");
  const { GENERATED } = await loadTs("data/freedict.source.ts", tmp, "freedict");

  assertDelimiterFree(ENTRIES);

  // Curated words first — they carry the examples — then whatever FreeDict
  // adds that they don't already cover. This order is what RICH_COUNT means.
  const seen = new Set();
  const core = [];
  const examples = [];

  for (const e of ENTRIES) {
    const id = e.dutch.toLowerCase();
    if (seen.has(id)) continue;
    seen.add(id);
    const code = GENDER_CODE[e.gender];
    if (!code) {
      throw new Error(
        `"${e.dutch}" has gender ${JSON.stringify(e.gender)} — expected "de", "het", "none" or "unknown"`
      );
    }
    core.push([e.dutch, e.english, code].join(FIELD));
    examples.push([e.example, e.exampleEn].join(FIELD));
  }
  const richCount = core.length;

  let skipped = 0;
  for (const [dutch, english] of GENERATED) {
    const id = dutch.toLowerCase();
    if (seen.has(id)) {
      skipped++;
      continue;
    }
    seen.add(id);
    // FreeDict carries no gender field at all, so strictly nothing here is
    // established. But "unknown" should mean "this might be a noun and we
    // don't know its article", not "we know nothing about this word" — and
    // FreeDict's own gloss settles the question for verbs, which it writes in
    // the infinitive ("to walk"). Marking those "none" keeps the unknown
    // count meaning what it says: nouns still missing an article, which is
    // work to be done, rather than verbs that were never going to have one.
    const looksLikeVerb = /^to\s/.test(english);
    core.push([dutch, english, looksLikeVerb ? GENDER_CODE.none : GENDER_CODE.unknown].join(FIELD));
  }

  writeFileSync(
    "src/data/core.generated.ts",
    tsModule(
      "// Every word: Dutch, English gloss, gender code\n" +
        "// (d = de, h = het, n = takes no article, u = article not established).",
      "CORE",
      core.join(RECORD)
    ) + `\n/** Words carrying an example sentence — the curated core, always first. */\nexport const RICH_COUNT = ${richCount};\n`
  );

  writeFileSync(
    "src/data/examples.generated.ts",
    tsModule(
      "// Example sentences, one line per word, aligned with the first RICH_COUNT\n" +
        "// lines of CORE. Imported lazily — see src/data/examples.ts.",
      "EXAMPLES",
      examples.join(RECORD)
    )
  );

  const kb = (s) => `${Math.round(s / 1024)} kB`;
  console.log(`curated words     ${richCount.toLocaleString()}`);
  console.log(`FreeDict added    ${(core.length - richCount).toLocaleString()} (${skipped.toLocaleString()} already covered)`);
  console.log(`total words       ${core.length.toLocaleString()}`);
  console.log(`core.generated    ${kb(core.join(RECORD).length)}`);
  console.log(`examples.generated ${kb(examples.join(RECORD).length)} (lazy)`);
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
